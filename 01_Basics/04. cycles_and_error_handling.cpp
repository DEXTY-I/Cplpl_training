#include <iostream>
#include <ctime>
// <ctime> — это заголовочный файл стандартной библиотеки, который содержит функции и типы для работы с системным временем и датой.

// ЧТО ВНУТРИ <ctime>
/*	
Основные типы данных:
	time_t — арифметический тип для хранения календарного времени.
	clock_t — тип для измерения тактов процессора.
	struct tm — структура с разбивкой времени на компоненты (год, месяц, день, час, минута, секунда).
Популярные функции:
	time() — возвращает текущее календарное время.
	clock() — возвращает количество тактов процессора, прошедших с запуска программы (полезно для замера скорости кода).
	ctime() — преобразует значение time_t в удобочитаемую строку с датой и временем (см. описание функции на CppStudio).
	difftime() — вычисляет разницу между двумя временными метками.
	localtime() / gmtime() — преобразуют time_t в структуру struct tm (для местного времени или времени UTC).
	strftime() — форматирует дату и время в виде строки по заданному шаблону.
*/

// *В современном C++ (начиная с C++11) для работы со временем рекомендуется исполльзовать более новую и безопасную библиотеку [std::chrono]

int main()
{
	setlocale(LC_ALL, "Russian");

	// ВИДЫ ЦИКЛОВ

	/*
	* for (со счетчиком): Применяется, когда точное число повторений заранее известно. 
	Конструкция содержит инициализацию, условие и шаг изменения счетчика.
	
	* while (с предусловием): Выполняет код до тех пор, пока истинно заданное условие. 
	Условие проверяется до выполнения тела цикла, поэтому при ложном условии код не выполнится ни разу.
	
	* do-while (с постусловием): Сначала выполняет тело цикла, а затем проверяет условие. 
	Гарантирует выполнение кода хотя бы один раз.

	* Range-based for (подиапазонный): Появился в C++11. 
	Удобно перебирает элементы контейнеров (например, векторов или массивов) или строк без ручного управления индексами.
	*/

	// УПРАВЛЕНИЕ ЦИКЛОМ

	// break: Полностью прерывает выполнение текущего цикла.
	// continue: Пропускает оставшуюся часть текущей итерации и переходит к следующей.

	//---------------------------------------------------------------------------------------------------------------//

	// ЦИКЛ while

	/* Общий вид цикла
	while (условие)
	{
		тело цикла (код, который повторяется)
	}
	*/
	
	//	Принцип действия:
	// 1. Проверка условия: Перед каждой итерацией программа проверяет значение в скобках (условие).
	// 2. Выполнение : Если условие истинно(не равно нулю / true), выполняется код в фигурных скобках.
	// 3. Повтор : После выполнения тела программа возвращается к проверке условия.Если условие ложно(false или 0), цикл завершается, и управление передается на код после цикла.

	// Простой пример, вывод чисел от 1 до 10:
	int i = 1; // инициализация счетчика
	while (i <= 10) // условие: пока i меньше или равно 5
	{
		std::cout << i << " ";
		i++; // увеличение счетчика (обязательно!)
	}
	std::cout << "\n";

	//    БЕСКОНЕЧНЫЙ ЦИКЛ:
	// Если условие никогда не станет ложным (например, while(true)), программа будет работать бесконечно. 
	// Внутри такого цикла нужно использовать оператор выхода break или return.

	//	 *Бесконеччный цикл:
	// Вместо бесконечного цикла + break/return рекомендуется использовать флаги (flag)
	// flag - булевая переменная
	/*
	while (flag)
	{
		....какой-то код...
		flag = False // Завершает итерации цикла
	}	
	*/ 

	//    Изменение переменной: 
	// Внутри цикла обязательно должно быть действие, которое изменяет переменные из условия. 
	// Если забыть увеличить счетчик (как i++ в примере выше), можно случайно создать бесконечный цикл.

	//---------------------------------------------------------------------------------------------------------------//

	// ЦИКЛ for

	/* Общий вид цикла
	for (инициализация; условие; шаги) 
	{
		тело цикла
	}
	
	* Инициализация: создание и настройка счетчика (выполняется один раз).
	* Условие : проверка перед каждым шагом; если оно ложно, цикл завершается.
	* Шаг(итерация) : изменение счетчика после выполнения тела цикла.
	** В цикле for можно пропускать любую из трех частей (инициализацию, условие или итерацию), оставляя точки с запятой на месте.
		Конструкция for (;;) — это классический бесконечный цикл в C++, где пропущены вообще все три выражения. По смыслу он полностью равен while (true).
	*/

	// Простой пример, вывод чисел от 0 до 9:
	for (int i = 0; i < 10; i++) 
	{
		std::cout << i << " ";
	}
	std::cout << "\n";

	// Вложенный цикл в C++ — это один цикл, который находится внутри тела другого цикла.	

	// ПРИМЕР:

	for (int i = 1; i <= 3; i++) { // Внешний цикл
		for (int j = 1; j <= 3; j++) { // Внутренний цикл
			std::cout << i << j << " ";
		}
	} 	
	// Вывод: 11 12 13 21 22 23 31 32 33
	std::cout << "\n";
	
	// Сложность вложенного цикла Big O - квадратичная 
	// Подробнее про сложность алгоритмов: https://habr.com/ru/articles/782608/
	// Чем выше сложность - тем медленнее алгоритм -> высокая сложность (не оптимальная) = говнокод
	
	//---------------------------------------------------------------------------------------------------------------//

	// ЦИКЛ do while

	/* Общий вид цикла
	do 
	{
		// тело цикла (выполняется перед проверкой)
	} while (условие);
	*/

	// Тоже самое, что и while, за исключением, что мы проверяем условие после выполнения кода (гарантирует 1 итерацию) 
	int age = 18;
	do
	{
		age--;
		std::cout << "С++ - классный язык!" << std::endl;
	} while (age >= 21);
	// Условие заведомо ложно, но код исполнится 1 раз. -> будет вывод: С++ - классный язык!

	//---------------------------------------------------------------------------------------------------------------//
	
	// РАНДОМ

	// Функция srand используется для инициализации (задания начального значения или «зерна») генератора псевдослучайных чисел, 
	// который затем используется функцией rand. Без вызова srand функция rand всегда возвращает одинаковую последовательность чисел при каждом запуске программы.
	for (int k = 0; k < 5; k++)
	{
		int number = rand() % 3;
		std::cout << number << " ";
	} // Запустите код несколько раз, вывод всегда будет одинаковый.
	std::cout << std::endl;

	srand(time(0));
	// КАК ЭТО РАБОТАЕТ
	/*  srand(seed)
	1) Зерно (seed): Аргумент seed определяет стартовую точку для математического алгоритма генерации чисел. Одинаковое зерно даёт одинаковый набор чисел.
	2) Текущее время: Чтобы последовательность менялась при каждом новом запуске, в качестве зерна передают текущее время с помощью функции time(0) или time(nullptr) из заголовочного файла <ctime>.
	3) Частота вызова: srand достаточно вызвать один раз! (ф-я rand, вызванная до вызова srand, будет иметь одинаковые значения)
	*/

	for (int k = 0; k < 5; k++)
	{
		int number = rand() % 3;
		std::cout << number << " ";
	} // После объявления srand вывод будет различным.
	std::cout << std::endl;

	// Функция rand() генерирует псевдослучайные целые числа в диапазоне от 0 до RAND_MAX (обычно не менее 32767).

	//---------------------------------------------------------------------------------------------------------------//

	// ОБРАБОТКА ПЛОХИХ ДАННЫХ
	// std::cin.ignore() — это метод стандартного потока ввода в C++, который извлекает и отбрасывает символы из буфера ввода.
	// std::cin.ignore(count, delim);
	// count — максимальное количество символов для удаления (по умолчанию 1)
	// delim — символ-разделитель (по умолчанию символ новой строки '\n'), на котором удаление останавливается.
	std::cin.ignore(32767, '\n'); // Удаляет 32767 символов ИЛИ пока не встретит '\n'.

	//std::cin.ignore(std::cin.rdbuf()->in_avail()); // Узнаёт кол-во символов в буфере и удаляет их все. МОЖЕТ РАБОТАТЬ НЕКОРРЕКТНО с некоторыми потоками ввода.
	// АЛЬТЕРНАТИВА:
	// Пропустить всё до следующего перевода строки включительно
	//std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');
	// Пропустить всё
	//std::cin.ignore(std::numeric_limits<std::streamsize>::max());

	// std::cin.clear() — это функция, которая сбрасывает флаги ошибок потока ввода и возвращает его в рабочее состояние
	//std::cin.clear();

	// std::cin.fail() — это метод потока ввода в C++, который возвращает логическое значение true, 
	// если последняя операция ввода завершилась с ошибкой (установлен бит состояния failbit), и false в противном случае.
	
	int number;
	// Алгоритм проверки и возобновления потока
	while (true) 
	{
		std::cout << "Введите целое число: ";
		std::cin >> number;

		// 1. Проверяем, успешный ли ввод
		if (std::cin.fail()) {
			std::cout << "Ошибка ввода! Вы ввели некорректные данные.\n";

			// 2. Восстанавливаем поток (сбрасываем флаги failbit/badbit)
			std::cin.clear();

			// 3. Очищаем буфер до конца строки
			std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n');

			continue; // Повторяем запрос
		}

		// Если все хорошо, выходим из цикла
		break;
	}

	bool is_find = 0;
	int num;
	// Ещё один подобный алгоритм
	while (!is_find)
	{
		std::cin >> num;
		if (std::cin.fail()) // 1. Проверяем корректность ввода. 
		{
			std::cin.clear();	// 2. Восстанавливаем поток (сбрасываем флаги failbit/badbit)
			std::cin.ignore(std::cin.rdbuf()->in_avail());	// 3. Очищаем буфер до конца строки
		}
		else {
			is_find = 1;
		}
	}
}

// ОПЕРАТОР goto
// goto - это инструмент безусловного перехода, который мгновенно передает управление программой на инструкцию, помеченную специальной меткой в пределах той же функции.
// Несмотря на то что в современном программировании goto считается плохой практикой из-за создания запутанного («спагетти») кода, в языке остаются ситуации, где его использование оправдано.
// Метка представляет собой обычный идентификатор с двоеточием. Оператор goto может ссылаться на метку, расположенную как выше, так и ниже по коду.
int age_check() 
{
    int age = 15;

    if (age < 18) {
        goto incomplete; // Прыжок к метке incomplete
    }

    std::cout << "Доступ разрешен.\n";
    
incomplete: // Метка
    std::cout << "Вход только для совершеннолетних.\n";
    return 0;
}
